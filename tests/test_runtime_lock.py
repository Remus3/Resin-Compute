"""Every requirements lock is hashed and matches its unhashed .in declaration.

MAIN ORDER 1925 item e (2026-10-15): keep an unhashed requirements.in and
generate requirements.txt from it with --generate-hashes, covering every
transitive. The runtime is stdlib-only, so requirements.in declares nothing and
the compiled requirements.txt carries only the pip-compile header. The dev pair
(requirements-dev.in / requirements-dev.txt, MAIN ORDER 0300) is graded by the
same function, so both pairs obey one rule:

1. the .in file exists beside the .txt file;
2. the .txt file is pip-compile output (the 3.11 header) whose recorded command
   generates hashes and names this .in file as its input;
3. every pin in the .txt file is `==` and carries at least one sha256 hash;
4. every requirement the .in file declares is pinned in the .txt file, at the
   same version when the .in pins one with `==`;
5. an EMPTY declaration compiles to an EMPTY closure - a pin in the .txt file
   with no declared root is a hand edit, not pip-compile output.

The install proof (a fresh venv per host interpreter plus the embedded runtime,
`pip install --require-hashes -r <lock>`) is an act, not a test; it is recorded
in the slice P5 report and its commit message. This file grades the bytes that
act used.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]

#: (declaration, compiled lock). The runtime pair is MAIN ORDER 1925 item e;
#: the dev pair is MAIN ORDER 0300.
PAIRS = (
    ("requirements.in", "requirements.txt"),
    ("requirements-dev.in", "requirements-dev.txt"),
)

_HEADER = re.compile(r"^# This file is autogenerated by pip-compile with [pP]ython 3\.11$", re.M)
_COMMAND = re.compile(r"^#\s+pip-compile\s+(.*)$", re.M)
_NAME = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")
_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)")
_HASH = re.compile(r"--hash=sha256:[0-9a-f]{64}\b")


def _norm(name: str) -> str:
    """PEP 503 name normalisation."""
    return re.sub(r"[-_.]+", "-", name).lower()


def declared(text: str) -> dict[str, str | None]:
    """Requirement name -> `==` version (or None) for every .in requirement."""
    out: dict[str, str | None] = {}
    for raw in text.splitlines():
        line = raw.split(" #", 1)[0].strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        pin = _PIN.match(line)
        if pin:
            out[_norm(pin.group(1))] = pin.group(2)
            continue
        name = _NAME.match(line)
        if name:
            out[_norm(name.group(1))] = None
    return out


def locked(text: str) -> tuple[dict[str, str], list[str], list[str]]:
    """(name -> version, unhashed names, non-`==` requirement lines)."""
    logical: list[str] = []
    buf = ""
    for raw in text.splitlines():
        stripped = raw.strip()
        if not buf and (not stripped or stripped.startswith("#")):
            continue
        if stripped.endswith("\\"):
            buf += stripped[:-1] + " "
            continue
        logical.append(buf + stripped)
        buf = ""
    if buf:
        logical.append(buf)
    entries: dict[str, str] = {}
    unhashed: list[str] = []
    floating: list[str] = []
    for line in logical:
        if line.startswith("-"):
            continue
        pin = _PIN.match(line)
        if not pin:
            floating.append(line.split()[0])
            continue
        name = _norm(pin.group(1))
        entries[name] = pin.group(2)
        if not _HASH.search(line):
            unhashed.append(name)
    return entries, unhashed, floating


def grade_pair(root: Path, in_name: str, txt_name: str) -> list[str]:
    """Every way the pair at `root` breaks the five rules in the docstring."""
    problems: list[str] = []
    src, lock = root / in_name, root / txt_name
    if not src.is_file():
        return [f"{in_name} is missing beside {txt_name}"]
    if not lock.is_file():
        return [f"{txt_name} is missing"]
    text = lock.read_text(encoding="utf-8")
    if not _HEADER.search(text):
        problems.append(f"{txt_name} lacks the pip-compile Python 3.11 header")
    command = _COMMAND.search(text)
    if not command:
        problems.append(f"{txt_name} records no pip-compile command")
    else:
        args = command.group(1).split()
        if "--generate-hashes" not in args:
            problems.append(f"{txt_name} was compiled without --generate-hashes")
        if not args or args[-1] != in_name:
            problems.append(f"{txt_name} was compiled from {args[-1:]} not {in_name}")
        if f"--output-file={txt_name}" not in args:
            problems.append(f"{txt_name} records a different --output-file")
    entries, unhashed, floating = locked(text)
    if unhashed:
        problems.append(f"{txt_name} pins without a hash: {unhashed}")
    if floating:
        problems.append(f"{txt_name} has non-== requirements: {floating}")
    decl = declared(src.read_text(encoding="utf-8"))
    for name, version in decl.items():
        if name not in entries:
            problems.append(f"{in_name} declares {name} but {txt_name} does not pin it")
        elif version is not None and entries[name] != version:
            problems.append(f"{name}: {in_name} pins {version}, {txt_name} pins {entries[name]}")
    if not decl and entries:
        problems.append(f"{in_name} declares nothing but {txt_name} pins {sorted(entries)}")
    return problems


@pytest.mark.parametrize(("in_name", "txt_name"), PAIRS)
def test_every_lock_is_hashed_and_matches_its_declaration(in_name: str, txt_name: str) -> None:
    assert grade_pair(REPO_ROOT, in_name, txt_name) == []


def test_the_runtime_declaration_is_still_empty_and_so_is_its_closure() -> None:
    """ADR-002: stdlib-only at runtime. A pin appearing here is a decision that
    must be made deliberately, with LICENSE_NOTES checked first."""
    assert declared((REPO_ROOT / "requirements.in").read_text(encoding="utf-8")) == {}
    entries, _, floating = locked((REPO_ROOT / "requirements.txt").read_text(encoding="utf-8"))
    assert entries == {} and floating == []


def test_the_dev_pair_is_not_graded_vacuously() -> None:
    """The dev lock is a real closure: more pins than declarations, all hashed."""
    decl = declared((REPO_ROOT / "requirements-dev.in").read_text(encoding="utf-8"))
    entries, unhashed, _ = locked((REPO_ROOT / "requirements-dev.txt").read_text(encoding="utf-8"))
    assert len(decl) >= 4 and len(entries) > len(decl) and unhashed == []


# ---------------------------------------------------------------------------
# Non-vacuity: each defect is reinstated on a COPY of the real pair and must red.
# ---------------------------------------------------------------------------

_SHA = "a" * 64


def _copy_pair(tmp_path: Path, in_name: str, txt_name: str) -> Path:
    for name in (in_name, txt_name):
        shutil.copyfile(REPO_ROOT / name, tmp_path / name)
    return tmp_path


def _append(path: Path, text: str) -> None:
    path.write_bytes(path.read_bytes() + text.encode("ascii"))


def test_a_hand_added_runtime_pin_with_no_declared_root_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[0])
    _append(root / "requirements.txt", f"requests==2.0.0 \\\n    --hash=sha256:{_SHA}\n")
    problems = grade_pair(root, *PAIRS[0])
    assert any("declares nothing" in p for p in problems), problems


def test_an_unhashed_pin_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[1])
    _append(root / "requirements-dev.txt", "pytest-xdist==3.0.0\n")
    problems = grade_pair(root, *PAIRS[1])
    assert any("without a hash" in p and "pytest-xdist" in p for p in problems), problems


def test_a_declaration_missing_from_the_lock_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[0])
    _append(root / "requirements.in", "requests==2.0.0\n")
    problems = grade_pair(root, *PAIRS[0])
    assert any("does not pin it" in p for p in problems), problems


def test_version_drift_between_declaration_and_lock_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[1])
    src = root / "requirements-dev.in"
    src.write_bytes(src.read_bytes().replace(b"ruff==0.16.10", b"ruff==0.16.11"))
    problems = grade_pair(root, *PAIRS[1])
    assert any(p.startswith("ruff:") for p in problems), problems


def test_a_hand_written_or_unhashed_compile_header_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[0])
    lock = root / "requirements.txt"
    lock.write_bytes(lock.read_bytes().replace(b"--generate-hashes ", b""))
    assert any("without --generate-hashes" in p for p in grade_pair(root, *PAIRS[0]))
    lock.write_bytes(b"# ResinCompute runtime deps: none\n")
    problems = grade_pair(root, *PAIRS[0])
    assert any("header" in p for p in problems) and any("no pip-compile" in p for p in problems)


def test_a_lock_compiled_from_the_wrong_input_reds(tmp_path: Path) -> None:
    root = _copy_pair(tmp_path, *PAIRS[0])
    lock = root / "requirements.txt"
    lock.write_bytes(lock.read_bytes().replace(b" requirements.in", b" requirements-dev.in"))
    assert any("compiled from" in p for p in grade_pair(root, *PAIRS[0]))


def test_a_missing_declaration_reds(tmp_path: Path) -> None:
    shutil.copyfile(REPO_ROOT / "requirements.txt", tmp_path / "requirements.txt")
    assert grade_pair(tmp_path, *PAIRS[0]) == ["requirements.in is missing beside requirements.txt"]
